from pathlib import Path
import re
from typing import Optional

import pandas as pd
import requests


# Dataset identifier on HDX
DATASET_ID = "ambulance-operations-in-northwest-syria-jan"

# HDX CKAN API endpoint
API_URL = f"https://data.humdata.org/api/3/action/package_show?id={DATASET_ID}"

# Local folder used to store downloaded Excel files and final CSV output
DATASET_DIR = Path("Dataset")
OUTPUT_FILE = DATASET_DIR / "ambulance_syria_merged.csv"


# Mapping month names to month numbers
MONTHS = {
    "jan": 1,
    "january": 1,
    "feb": 2,
    "february": 2,
    "mar": 3,
    "march": 3,
    "apr": 4,
    "april": 4,
    "may": 5,
    "jun": 6,
    "june": 6,
    "jul": 7,
    "july": 7,
    "aug": 8,
    "august": 8,
    "sep": 9,
    "september": 9,
    "oct": 10,
    "october": 10,
    "nov": 11,
    "november": 11,
    "dec": 12,
    "december": 12,
}


def download_file(url: str, output_path: Path) -> None:
    """
    Download a file from a URL and save it locally.

    Parameters
    ----------
    url:
        Direct file URL.
    output_path:
        Local path where the file should be saved.
    """
    response = requests.get(url, stream=True, timeout=60)
    response.raise_for_status()

    with open(output_path, "wb") as file:
        for chunk in response.iter_content(chunk_size=8192):
            if chunk:
                file.write(chunk)


def fetch_xlsx_resources() -> list[dict]:
    """
    Fetch dataset resources from HDX and return only Excel files.

    Returns
    -------
    list[dict]
        A list of HDX resource objects that point to Excel files.
    """
    print("Fetching dataset resources from HDX...")

    response = requests.get(API_URL, timeout=60)
    response.raise_for_status()

    data = response.json()

    if not data.get("success"):
        raise RuntimeError("Failed to fetch dataset information from HDX API.")

    resources = data["result"]["resources"]

    xlsx_resources = [
        resource
        for resource in resources
        if resource.get("format", "").lower() == "xlsx"
        or resource.get("name", "").lower().endswith(".xlsx")
        or resource.get("url", "").lower().endswith(".xlsx")
    ]

    return xlsx_resources


def download_dataset_files() -> None:
    """
    Download all Excel files related to the ambulance operations dataset.
    Existing files are skipped to avoid duplicate downloads.
    """
    DATASET_DIR.mkdir(exist_ok=True)

    xlsx_resources = fetch_xlsx_resources()

    print(f"Found {len(xlsx_resources)} Excel files.")

    for resource in xlsx_resources:
        file_url = resource.get("url")

        if not file_url:
            print("Skipping resource without URL.")
            continue

        file_name = resource.get("name") or file_url.split("/")[-1]

        if not file_name.lower().endswith(".xlsx"):
            file_name += ".xlsx"

        output_path = DATASET_DIR / file_name

        if output_path.exists():
            print(f"Already exists, skipping: {file_name}")
            continue

        print(f"Downloading: {file_name}")

        try:
            download_file(file_url, output_path)
            print(f"Saved to: {output_path}")
        except Exception as error:
            print(f"Failed to download {file_name}: {error}")


def extract_month_year(file_name: str) -> tuple[int, int]:
    """
    Extract year and month from an Excel file name.

    Expected examples:
    - Ambulance-Syria-May-2025.xlsx
    - Ambulance-Syria-January-2024.xlsx

    Returns
    -------
    tuple[int, int]
        Year and month number.
    """
    name = file_name.lower()

    match = re.search(r"ambulance-syria-([a-z]+)-(\d{4})", name)

    if not match:
        raise ValueError(f"Cannot extract month/year from file name: {file_name}")

    month_name = match.group(1)
    year = int(match.group(2))

    month = MONTHS.get(month_name)

    if month is None:
        raise ValueError(f"Unknown month name '{month_name}' in file: {file_name}")

    return year, month


def clean_columns(df: pd.DataFrame) -> pd.DataFrame:
    """
    Clean column names and remove empty columns and empty rows.

    This function removes columns like 'Unnamed' and normalizes spaces
    inside column names.
    """
    df = df.copy()

    # Remove empty columns generated by Excel formatting
    df = df.loc[:, ~df.columns.astype(str).str.contains("^Unnamed", case=False)]

    # Clean column names
    df.columns = (
        df.columns.astype(str)
        .str.strip()
        .str.replace("\n", " ", regex=False)
        .str.replace(r"\s+", " ", regex=True)
    )

    # Remove fully empty rows
    df = df.dropna(how="all")

    return df


def read_ambulance_excel(file_path: Path) -> Optional[pd.DataFrame]:
    """
    Read one ambulance Excel file and add metadata columns.

    Parameters
    ----------
    file_path:
        Path to the Excel file.

    Returns
    -------
    Optional[pandas.DataFrame]
        Cleaned DataFrame with metadata columns, or None if reading fails.
    """
    try:
        year, month = extract_month_year(file_path.name)

        # The actual table header starts on the third row in the Excel sheet
        df = pd.read_excel(
            file_path,
            sheet_name="Ambulance",
            header=2,
            engine="openpyxl",
        )

        df = clean_columns(df)

        # Add source metadata to track the origin of each row
        df.insert(0, "source_file", file_path.name)
        df.insert(1, "report_year", year)
        df.insert(2, "report_month", month)
        df.insert(3, "report_period", pd.to_datetime(f"{year}-{month:02d}-01"))

        return df

    except Exception as error:
        print(f"Failed to read {file_path.name}: {error}")
        return None


def merge_excel_files() -> None:
    """
    Merge all downloaded ambulance Excel files into one CSV file.
    """
    if not DATASET_DIR.exists():
        raise FileNotFoundError(f"Folder not found: {DATASET_DIR}")

    excel_files = list(DATASET_DIR.glob("*.xlsx"))

    if not excel_files:
        raise FileNotFoundError(f"No Excel files found in: {DATASET_DIR}")

    # Sort files from newest to oldest based on year and month
    excel_files = sorted(
        excel_files,
        key=lambda file: extract_month_year(file.name),
        reverse=True,
    )

    print("\nFiles will be merged in this order:")

    for file in excel_files:
        year, month = extract_month_year(file.name)
        print(f"- {file.name} -> {year}-{month:02d}")

    all_dataframes = []

    for file_path in excel_files:
        print(f"\nReading: {file_path.name}")

        df = read_ambulance_excel(file_path)

        if df is not None:
            print(f"Rows: {len(df)} | Columns: {len(df.columns)}")
            all_dataframes.append(df)

    if not all_dataframes:
        raise RuntimeError("No files were successfully read.")

    merged_df = pd.concat(all_dataframes, ignore_index=True)

    # Keep final dataset ordered from newest to oldest
    merged_df = merged_df.sort_values(
        by=["report_period"],
        ascending=False,
        kind="stable",
    )

    # Save CSV with UTF-8 BOM to support Arabic text in Excel
    merged_df.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8-sig",
    )

    print("\nDone.")
    print(f"Merged rows: {len(merged_df)}")
    print(f"Saved CSV file to: {OUTPUT_FILE}")


def main() -> None:
    """
    Main pipeline:
    1. Download Excel files from HDX.
    2. Merge all Excel files into one CSV file.
    """
    download_dataset_files()
    merge_excel_files()


if __name__ == "__main__":
    main()